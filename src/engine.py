class Engine:

    def __init__(self, file):
        self.chunker = Chunker()
        self.file = file
        self.generator = Generator()

        

    
    def run(self):
        self.chunker.run()
        self.indexer = Indexer(self.file)

        self.indexer.index()
        self.indexer.load()
        
        res = self.indexer.search(queries)
        
        contexts = [
        source["content"]
        for source in res[0]['results']
]

        

        for query in queries:
            answer = self.generator.generate_v2(
                question=query,
                contexts=contexts,
            )
            print(answer)

        

        

    
    def retrieve_data(self, data):
        results = []
        for i, item in enumerate(data):
            results.append({
                "question_id": f"q{i + 1}",
                "question": item.get("query", ""),
                "retrieved_sources" : item["results"]
            })
        
        with open("test.json", 'w') as f:
            json.dump(results, f, indent=2)
